#!/bin/bash
# Напоминание правил «пиши просто» для русского текста, сжатое под разговор.
# Вставляется в контекст модели через UserPromptSubmit → additionalContext.
#
# Устройство. Хук платится за КАЖДОЕ сообщение, и копии остаются в истории, поэтому
# он несёт только то, что проседает в разговоре. Тонкости оформления документа сюда
# не входят: они живут в скиле и подгружаются под большой текст. Полный свод уходит
# один раз за сессию, дальше идёт короткое напоминание, а служебные сообщения молчат.
#
# Настройки через переменные окружения:
#   SIMPLE_LANGUAGE_FULL_EVERY=10  — вернуть повторы: каждое N-е сообщение получает полный свод
#   SIMPLE_LANGUAGE_MODE=full      — всегда полный свод
#   SIMPLE_LANGUAGE_MODE=off       — молчать
#
# Оговорка. Лозунг «пиши, сокращай» сознательно НЕ взят: модель читает его буквально как
# «короче» и снова начинает рубить мысли до обрывков, что работает против пункта 2.

SL_INPUT=$(cat)
SL_FULL='ПИШИ ПРОСТО — правила русского текста для человека (чат и документы; не для кода, git-коммитов и не для текста на других языках). 1) Веди с главного: первое предложение это ответ, детали идут после него. 2) ГЛАВНОЕ И ЧАЩЕ ВСЕГО НАРУШАЕМОЕ: пиши развёрнутыми простыми предложениями, а не сжатыми тезисами. Каждая мысль это законченное предложение с подлежащим и сказуемым. Обрубки вроде «Ритм — недельный, не поток» разворачивай в два-три обычных предложения. Не строй фразу через «не X, а Y» и через тире вместо глагола. 3) Объём не ограничен: длинный понятный текст лучше короткого плотного. Убрать лишние слова это одна десятая работы, а девять десятых это положить на их место факты, примеры и объяснения. 4) Пиши буквально, без метафор и образов, и убирай усилители «очень», «весьма», «вполне»: они не добавляют факта. 5) Специальный термин из любой области поясняй один раз и не прячь в скобки весь жаргон подряд; слова, которые человек употребил сам, не заменяй и не поясняй. 6) Доли вместо процентов: «4 из 10» понятнее, чем «39%». Число объясняй: что оно значит для человека. 7) Форматируй щедро, но по делу: заголовки, списки, короткие абзацы по 2–4 предложения, воздух. Маркированный список это равноправные пункты, нумерованный это шаги по очереди, абзац это связное рассуждение. Пункт длиннее одного предложения был абзацем. Значимое слово ставь в начало заголовка, пункта и абзаца. Оговорку давай блок-цитатой, а сайт кликабельной ссылкой с осмысленным текстом. 8) Перед отправкой прочти вслух: вопрос не «покороче ли стало», а «понятно ли с первого раза» и «звучит ли как живая речь». Тонкости оформления (таблицы, картинки и alt-текст, уровни заголовков, доступность) и полный свод с примерами лежат в скиле «pishi-prosto» — зови его для документов и больших текстов.'
SL_SHORT='ПИШИ ПРОСТО (короткое напоминание): пиши развёрнутыми простыми предложениями с подлежащим и сказуемым, а не сжатыми тезисами; веди с главного; пиши буквально, без метафор; специальный термин поясняй один раз; доли вместо процентов; форматируй щедро — заголовки, списки, короткие абзацы, воздух. Правило для русского текста, не для кода и git-коммитов. Полный свод — скил pishi-prosto.'
export SL_INPUT SL_FULL SL_SHORT

[ "${SIMPLE_LANGUAGE_MODE:-}" = "off" ] && exit 0

if [ "${SIMPLE_LANGUAGE_MODE:-}" = "full" ] || ! command -v python3 >/dev/null 2>&1; then
  printf '{"hookSpecificOutput":{"hookEventName":"UserPromptSubmit","additionalContext":"%s"}}\n' "$SL_FULL"
  exit 0
fi

python3 <<'PYEOF'
import hashlib, json, os, re, sys, time

full = os.environ.get('SL_FULL', '')
short = os.environ.get('SL_SHORT', '')
try:
    data = json.loads(os.environ.get('SL_INPUT') or '{}')
except Exception:
    data = {}

prompt = (data.get('prompt') or '').strip()
sid = data.get('session_id') or ''

# 1. Служебные сообщения правил письма не требуют, поэтому напоминание им не нужно.
SKIP = {
    'да', 'нет', 'ок', 'окей', 'ага', 'угу', 'давай', 'стоп', 'хватит', 'спасибо',
    'ясно', 'понял', 'поехали', 'дальше', 'продолжай', 'go', 'ok', 'okay', 'yes',
    'no', 'y', 'n', 'sure', 'thanks', 'stop', 'continue', 'next',
}
low = prompt.lower().strip(' .!?,;:')
is_path = bool(re.fullmatch(r'[\w./~@-]+\.[A-Za-z0-9]{1,5}', prompt))
is_url = bool(re.fullmatch(r'https?://\S+', prompt))
if not prompt or prompt.startswith('/') or low in SKIP or is_path or is_url:
    sys.exit(0)

# 2. Полный свод уходит первым сообщением сессии, дальше идёт короткое напоминание.
#    Переменная SIMPLE_LANGUAGE_FULL_EVERY возвращает повторы: с ней полный свод
#    приходит каждый N-й ход.
every = 0
raw = os.environ.get('SIMPLE_LANGUAGE_FULL_EVERY')
if raw:
    try:
        every = max(1, int(raw))
    except ValueError:
        every = 0

n = 1
if sid:
    state_dir = os.path.join(os.path.expanduser('~'), '.claude', '.simple-language')
    try:
        os.makedirs(state_dir, exist_ok=True)
        now = time.time()
        for name in os.listdir(state_dir):       # старые сессии убираем через неделю
            p = os.path.join(state_dir, name)
            if now - os.path.getmtime(p) > 7 * 24 * 3600:
                os.remove(p)
    except Exception:
        pass
    path = os.path.join(state_dir, hashlib.sha1(sid.encode()).hexdigest()[:16])
    try:
        with open(path, encoding='utf-8') as f:
            n = int(f.read().strip()) + 1
    except Exception:
        n = 1
    try:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(str(n))
    except Exception:
        pass

text = full if (every and (n - 1) % every == 0) or (not every and n == 1) else short
out = {'hookSpecificOutput': {'hookEventName': 'UserPromptSubmit', 'additionalContext': text}}
print(json.dumps(out, ensure_ascii=False))
PYEOF
