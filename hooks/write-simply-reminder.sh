#!/bin/bash
# Напоминание правил «пиши просто + форматируй щедро» для русского текста.
# Вставляется в контекст модели через UserPromptSubmit → additionalContext.
#
# Устройство. Хук платится за КАЖДОЕ сообщение, и копии остаются в истории, поэтому
# полный свод уходит редко, а между ним идёт короткое напоминание на четверть длины.
# Служебные сообщения («да», «/команда», путь к файлу) не получают ничего.
#
# Настройки через переменные окружения:
#   SIMPLE_LANGUAGE_FULL_EVERY=10  — каждое N-е сообщение получает полный свод (по умолчанию 10)
#   SIMPLE_LANGUAGE_MODE=full      — всегда полный свод, как было раньше
#   SIMPLE_LANGUAGE_MODE=off       — молчать
#
# Оговорка. Лозунг «пиши, сокращай» сознательно НЕ взят: модель читает его буквально как
# «короче» и снова начинает рубить мысли до обрывков, что работает против пункта 2.

SL_INPUT=$(cat)
SL_FULL='ПИШИ ПРОСТО — правило для русского текста (чат и документы; не для кода, git-коммитов и не для текста на других языках): 1) Веди с главного — первое предложение это ответ. 2) ГЛАВНОЕ И ЧАЩЕ ВСЕГО НАРУШАЕМОЕ: пиши развёрнутыми простыми предложениями, а не сжатыми тезисами. Каждая мысль — законченное предложение с подлежащим и сказуемым. Обрубки вроде «Ритм — недельный, не поток» разворачивай в два-три обычных предложения. Не строй фразы через «не X, а Y» и через тире вместо глагола. 3) Объём не ограничен: длинный понятный текст лучше короткого плотного, читаемость даёт форматирование, а не сокращение. Убрать лишние слова — это одна десятая работы; девять десятых — положить на их место факты, примеры и объяснения. 4) Без метафор и образов — пиши буквально, что происходит. 5) Специальный термин из ЛЮБОЙ области (не только код) делай понятным, но не прячь весь жаргон: изредка оставляй термин с пояснением в скобках, чтобы читатель его усваивал, а не всё подряд в скобки, и поясняй термин один раз. Слова, которые читатель использует сам (например «deploy»), ему знакомы — не заменяй и не поясняй. 6) Доли вместо процентов («4 из 10», не «39%»). 7) Форматируй щедро, но по делу: заголовки, списки, таблицы, выделения, воздух. Приём выбирай по содержимому: маркированный список — равноправные пункты без порядка; нумерованный (1,2,3) — шаги по очереди (не сваливай в один абзац); абзац — когда мысли связаны рассуждением («поэтому», «но»). Абзац короткий, 2–4 предложения; новый топик или шаг — новый абзац с пустой строкой. Пункт длиннее одного предложения был абзацем; детали пункта — вложенными подпунктами; пункты по одному образцу; списка из одного пункта не бывает. Документ распадается на фрагменты (его сканируют до чтения): длинный раздел — короткий зачин плюс несколько помеченных подпунктов, по одному на мысль; дробление рекурсивно, стены не должно быть ни на каком уровне. Значимое слово ставь в начало заголовка, пункта и абзаца — сканируют по первым словам. Структуру держат заголовки (####, #####), а не жирный пункт; уровни не перепрыгивай (за ## идёт ###). Оговорку или примечание — блок-цитатой «>». Тонкости форматирования (таблицы, картинки и alt-текст, осмысленный текст ссылки) — в скиле pishi-prosto. 8) Каждый сайт — кликабельной ссылкой. 9) Перед отправкой перечитай и прочти вслух: не «покороче ли стало», а «понятно ли с первого раза» и «звучит ли как живая речь» — обрубок на глаз выглядит нормально, а вслух слышен сразу. Правило не про тему: оно одинаково работает в разработке, деньгах, здоровье, документах и обычном разговоре. Полный свод — скил «pishi-prosto» (зови его при работе с документами и большими текстами).'
SL_SHORT='ПИШИ ПРОСТО (короткое напоминание): пиши развёрнутыми простыми предложениями с подлежащим и сказуемым, а не сжатыми тезисами; веди с главного; пиши буквально, без метафор; специальный термин поясняй один раз; доли вместо процентов; форматируй щедро — заголовки, списки, короткие абзацы, воздух. Правило для русского текста, не для кода и git-коммитов. Полный свод — скил pishi-prosto.'
export SL_INPUT SL_FULL SL_SHORT

[ "${SIMPLE_LANGUAGE_MODE:-}" = "off" ] && exit 0

if [ "${SIMPLE_LANGUAGE_MODE:-}" = "full" ] || ! command -v python3 >/dev/null 2>&1; then
  printf '{"hookSpecificOutput":{"hookEventName":"UserPromptSubmit","additionalContext":"%s"}}\n' "$SL_FULL"
  exit 0
fi

python3 <<'PYEOF'
import hashlib, json, os, re, sys, time

full = os.environ.get('SL_FULL', '')
short = os.environ.get('SL_SHORT', '')
try:
    data = json.loads(os.environ.get('SL_INPUT') or '{}')
except Exception:
    data = {}

prompt = (data.get('prompt') or '').strip()
sid = data.get('session_id') or ''

# 1. Служебные сообщения правил письма не требуют, поэтому напоминание им не нужно.
SKIP = {
    'да', 'нет', 'ок', 'окей', 'ага', 'угу', 'давай', 'стоп', 'хватит', 'спасибо',
    'ясно', 'понял', 'поехали', 'дальше', 'продолжай', 'go', 'ok', 'okay', 'yes',
    'no', 'y', 'n', 'sure', 'thanks', 'stop', 'continue', 'next',
}
low = prompt.lower().strip(' .!?,;:')
is_path = bool(re.fullmatch(r'[\w./~@-]+\.[A-Za-z0-9]{1,5}', prompt))
is_url = bool(re.fullmatch(r'https?://\S+', prompt))
if not prompt or prompt.startswith('/') or low in SKIP or is_path or is_url:
    sys.exit(0)

# 2. Полный свод уходит редко, короткое напоминание — в остальные ходы.
try:
    every = max(1, int(os.environ.get('SIMPLE_LANGUAGE_FULL_EVERY') or 10))
except ValueError:
    every = 10

n = 1
if sid:
    state_dir = os.path.join(os.path.expanduser('~'), '.claude', '.simple-language')
    try:
        os.makedirs(state_dir, exist_ok=True)
        now = time.time()
        for name in os.listdir(state_dir):       # старые сессии убираем через неделю
            p = os.path.join(state_dir, name)
            if now - os.path.getmtime(p) > 7 * 24 * 3600:
                os.remove(p)
    except Exception:
        pass
    path = os.path.join(state_dir, hashlib.sha1(sid.encode()).hexdigest()[:16])
    try:
        with open(path, encoding='utf-8') as f:
            n = int(f.read().strip()) + 1
    except Exception:
        n = 1
    try:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(str(n))
    except Exception:
        pass

text = full if (n - 1) % every == 0 else short
out = {'hookSpecificOutput': {'hookEventName': 'UserPromptSubmit', 'additionalContext': text}}
print(json.dumps(out, ensure_ascii=False))
PYEOF
